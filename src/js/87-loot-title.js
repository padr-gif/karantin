// ================= в окне обыска над вещами — название того, что открыто («Книжный шкаф 0/10»), а не «Здесь» =================
// Заголовок окна сверху на телефоне закрывают подсказки (обучение, уведомления), поэтому название повторяется у списка.
// Берётся из заголовка окна после всех onPanel, так что подписи вроде «Ящик · Еда и вода» тоже попадают сюда.
onPanel(() => {
  if (!panel || panel.kind !== 'loot') return;
  const e = $('lootHere'), t = $('pnTitle'); if (!e || !t || !e.firstChild) return;
  const name = (t.textContent || '').trim(); if (name) e.firstChild.textContent = name + ' ';
});
