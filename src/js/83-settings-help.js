function helpRender() {
  const ul = $('helpList'); if (!ul) return; ul.textContent = '';
  for (const t of HELP[helpTab][1]) ul.appendChild(mk('li', '', t));
  const tabs = $('helpTabs'); if (tabs) [...tabs.children].forEach((b, k) => b.classList.toggle('on', k === helpTab));
  ul.scrollTop = 0;
}
